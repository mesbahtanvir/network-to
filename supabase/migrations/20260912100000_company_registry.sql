-- One company, one displayed name: the domain row mirrors its company so the sign-up trigger
-- and validate_company_domain keep reading company_domains exactly as before.
create or replace function private.sync_company_domain_names()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare derived_key text;
begin
  if tg_table_name = 'companies' then
    update public.company_domains d
      set company_name = new.name, industry = new.industry
      where d.company_key = new.key
        and (d.company_name is distinct from new.name or d.industry is distinct from new.industry);
    return new;
  end if;

  -- A domain inserted without a company (older tooling, manual SQL) becomes its own company
  -- so the registry invariant "every domain belongs to one company" always holds.
  if new.company_key is null then
    derived_key := trim(both '-' from regexp_replace(lower(coalesce(new.company_name, '')), '[^a-z0-9]+', '-', 'g'));
    if derived_key = '' or derived_key !~ '^[a-z0-9][a-z0-9-]{0,62}$' then
      derived_key := trim(both '-' from regexp_replace(lower(new.domain), '[^a-z0-9]+', '-', 'g'));
    end if;
    insert into public.companies (key, name, industry, website_url, coverage_clause, status)
    values (derived_key, new.company_name, new.industry, 'https://' || new.domain, 'launch', new.status)
    on conflict (key) do nothing;
    new.company_key := derived_key;
  end if;

  select c.name, c.industry into new.company_name, new.industry
  from public.companies c
  where c.key = new.company_key;
  return new;
end;
$$;

revoke all on function private.sync_company_domain_names() from public, anon, authenticated, service_role;

drop trigger if exists companies_sync_domain_names on public.companies;
create trigger companies_sync_domain_names after insert or update of name, industry on public.companies
for each row execute function private.sync_company_domain_names();

drop trigger if exists company_domains_sync_names on public.company_domains;
create trigger company_domains_sync_names before insert or update of company_key on public.company_domains
for each row execute function private.sync_company_domain_names();

