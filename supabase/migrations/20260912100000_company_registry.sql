-- Company registry (feature 002, verified company marks).
-- The registry becomes one row per company (public.companies) with one or more work-email
-- domains (public.company_domains). Sign-up eligibility still reads company_domains.status;
-- company marks (next migration) read companies.status. Expands the launch registry to
-- 249 well-known North American technology companies and employers, each recorded with
-- the coverage clause that admitted it (a: index constituent or its subsidiary, b: private with
-- at least 1,000 employees, c: at least 200 engineering staff in Toronto, launch: carried over
-- from the initial registry). Re-runnable. No operator step.

create table if not exists public.companies (
  key text primary key check (key ~ '^[a-z0-9][a-z0-9-]{0,62}$'),
  name text not null check (char_length(name) between 1 and 120),
  industry text not null check (char_length(industry) between 1 and 120),
  website_url text check (website_url is null or (website_url ~ '^https://' and char_length(website_url) <= 200)),
  coverage_clause text not null check (coverage_clause in ('a', 'b', 'c', 'launch')),
  status text not null default 'approved' check (status in ('approved', 'review_pending', 'rejected')),
  mark_status text not null default 'not_yet_fetched'
    check (mark_status in ('not_yet_fetched', 'available', 'no_icon_published', 'fetch_failed', 'withheld')),
  mark_version integer not null default 0 check (mark_version >= 0),
  mark_path text check (mark_path is null or mark_path ~ '^[a-z0-9][a-z0-9-]{0,62}/[0-9]+\.(png|jpg)$'),
  mark_content_type text check (mark_content_type is null or mark_content_type in ('image/png', 'image/jpeg')),
  mark_fetched_at timestamptz,
  mark_source_url text check (mark_source_url is null or char_length(mark_source_url) <= 500),
  mark_failure_reason text check (mark_failure_reason is null or char_length(mark_failure_reason) <= 300),
  mark_refresh_requested boolean not null default false,
  mark_claimed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

