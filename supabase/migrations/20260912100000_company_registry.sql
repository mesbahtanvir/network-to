    if derived_key = '' or derived_key !~ '^[a-z0-9][a-z0-9-]{0,62}$' then
      derived_key := trim(both '-' from regexp_replace(lower(row_record.domain), '[^a-z0-9]+', '-', 'g'));
    end if;
    insert into public.companies (key, name, industry, website_url, coverage_clause, status)
    values (derived_key, row_record.company_name, row_record.industry, 'https://' || row_record.domain, 'launch', row_record.status)
    on conflict (key) do nothing;
    update public.company_domains set company_key = derived_key where domain = row_record.domain;
  end loop;
